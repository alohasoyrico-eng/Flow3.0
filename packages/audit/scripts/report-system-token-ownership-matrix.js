const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../../..");
const SOURCE_ROOT = path.join(ROOT, "packages/tokens/source");
const SOURCE_MANIFEST = path.join(SOURCE_ROOT, "source-manifest.json");
const OUTPUT_MANIFEST = path.join(ROOT, "packages/tokens/dist/token-output-manifest.json");
const PACKAGE_JSON = path.join(ROOT, "package.json");
const TOKENS_PACKAGE_JSON = path.join(ROOT, "packages/tokens/package.json");
const OUT_JSON = path.join(ROOT, "docs/audits/system-token-ownership-matrix.json");
const OUT_MD = path.join(ROOT, "docs/audits/system-token-ownership-matrix.md");
const CHECK = process.argv.includes("--check");

const REQUIRED_SOURCE_FAMILIES = {
  foundation: [
    "accessibility",
    "depth",
    "energy",
    "frame",
    "growth",
    "iconography",
    "momentum",
    "state",
    "symbol",
    "tone",
    "voice",
  ],
  primitive: [
    "breakpoints",
    "charts",
    "color",
    "density",
    "disabled",
    "duration",
    "elevation",
    "email-channel",
    "focus",
    "iconography",
    "loading",
    "maps",
    "measurement",
    "message",
    "motion-curves",
    "radius",
    "research",
    "spacing",
    "typography",
  ],
};

const REQUIRED_OUTPUTS = [
  "packages/tokens/styles/tokens.css",
  "packages/tokens/tokens.json",
  "packages/tokens/src/generated/tokens.ts",
  "packages/tokens/dist/flutter/flow_tokens.dart",
  "packages/tokens/dist/android/flow_tokens.xml",
  "packages/tokens/dist/ios/FlowTokens.swift",
  "packages/react/src/internal/email-token-values.js",
];

const GENERATED_HEADERS = new Map([
  ["packages/tokens/dist/flutter/flow_tokens.dart", "Generated by Style Dictionary. Do not edit by hand."],
  ["packages/tokens/dist/android/flow_tokens.xml", "Generated by Style Dictionary. Do not edit by hand."],
  ["packages/tokens/dist/ios/FlowTokens.swift", "Generated by Style Dictionary. Do not edit by hand."],
]);

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function sha256(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function rel(file) {
  return path.relative(ROOT, file);
}

function existsRel(file) {
  return fs.existsSync(path.join(ROOT, file));
}

function walkTokenFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) walkTokenFiles(fullPath, out);
    if (entry.isFile() && entry.name.endsWith(".tokens.json")) out.push(fullPath);
  }
  return out.sort();
}

function tokenCount(file) {
  return Object.keys(readJson(file)).length;
}

function gate(id, passed, evidence, failMessage) {
  return {
    id,
    status: passed ? "PASS" : "FAIL",
    evidence,
    failMessage: passed ? null : failMessage,
  };
}

function sourceRows() {
  const rows = [];
  for (const [layer, families] of Object.entries(REQUIRED_SOURCE_FAMILIES)) {
    for (const family of families) {
      const file = `packages/tokens/source/${layer === "foundation" ? "foundations" : "primitives"}/${family}.tokens.json`;
      const fullPath = path.join(ROOT, file);
      const exists = fs.existsSync(fullPath);
      rows.push({
        layer,
        family,
        owner: `Flow ${layer} token source`,
        file,
        exists,
        tokenCount: exists ? tokenCount(fullPath) : 0,
        status: exists && tokenCount(fullPath) > 0 ? "PASS" : "FAIL",
      });
    }
  }
  return rows;
}

function outputRows(outputManifest) {
  const manifestOutputs = new Map((outputManifest.outputs ?? []).map((output) => [output.file, output]));
  return REQUIRED_OUTPUTS.map((file) => {
    const fullPath = path.join(ROOT, file);
    const exists = fs.existsSync(fullPath);
    const manifest = manifestOutputs.get(file);
    const actualSha = exists ? sha256(fullPath) : null;
    const content = exists ? fs.readFileSync(fullPath, "utf8") : "";
    const generatedHeader = GENERATED_HEADERS.get(file);
    return {
      file,
      owner: "Style Dictionary build output",
      source: "packages/tokens/source/**/*.tokens.json",
      exists,
      manifestSha: manifest?.sha256 ?? null,
      actualSha,
      matchesManifest: exists && Boolean(manifest) && actualSha === manifest.sha256,
      hasGeneratedHeader: generatedHeader ? content.includes(generatedHeader) : true,
      status: exists && Boolean(manifest) && actualSha === manifest.sha256 && (!generatedHeader || content.includes(generatedHeader)) ? "PASS" : "FAIL",
    };
  });
}

function main() {
  const allTokenSourceFiles = walkTokenFiles(SOURCE_ROOT).map(rel);
  const legacyFlatSource = "packages/tokens/source/flow.tokens.json";
  const sourceManifest = fs.existsSync(SOURCE_MANIFEST) ? readJson(SOURCE_MANIFEST) : null;
  const outputManifest = fs.existsSync(OUTPUT_MANIFEST) ? readJson(OUTPUT_MANIFEST) : null;
  const packageJson = readJson(PACKAGE_JSON);
  const tokensPackageJson = readJson(TOKENS_PACKAGE_JSON);
  const sources = sourceRows();
  const outputs = outputManifest ? outputRows(outputManifest) : [];
  const missingRequiredSources = sources.filter((row) => row.status !== "PASS");
  const failingOutputs = outputs.filter((row) => row.status !== "PASS");
  const unownedSourceFiles = allTokenSourceFiles.filter((file) => (
    !file.startsWith("packages/tokens/source/foundations/")
    && !file.startsWith("packages/tokens/source/primitives/")
    && !file.startsWith("packages/tokens/source/docs/")
    && !file.startsWith("packages/tokens/source/decision-queues/")
  ));
  const buildScript = packageJson.scripts?.["build:tokens"] ?? null;
  const packageExports = tokensPackageJson.exports ?? {};
  const requiredExportTargets = [
    "./tokens.json",
    "./styles.css",
    "./flutter",
    "./android",
    "./ios",
  ];
  const missingExports = requiredExportTargets.filter((key) => !packageExports[key]);
  const currentSourceTokenCount = allTokenSourceFiles.reduce((total, file) => total + tokenCount(path.join(ROOT, file)), 0);
  const gates = [
    gate(
      "required-source-families-owned",
      missingRequiredSources.length === 0,
      { missingRequiredSources },
      "One or more required foundation/primitive token source families are missing or empty.",
    ),
    gate(
      "no-legacy-flat-source",
      !existsRel(legacyFlatSource),
      { file: legacyFlatSource, exists: existsRel(legacyFlatSource) },
      "Legacy flat token source can bypass family ownership.",
    ),
    gate(
      "no-unowned-token-source-files",
      unownedSourceFiles.length === 0,
      { unownedSourceFiles },
      "Token source files must live under foundations, primitives, docs, or decision-queues.",
    ),
    gate(
      "source-manifest-current",
      Boolean(sourceManifest) && sourceManifest.counts?.total === currentSourceTokenCount,
      {
        manifestTotal: sourceManifest?.counts?.total ?? null,
        currentTotal: currentSourceTokenCount,
      },
      "Token source manifest is missing or stale.",
    ),
    gate(
      "style-dictionary-build-script-owned",
      buildScript === "node scripts/build-tokens.mjs",
      { buildScript },
      "Root build:tokens must run the Style Dictionary token builder.",
    ),
    gate(
      "output-manifest-present",
      Boolean(outputManifest),
      { file: rel(OUTPUT_MANIFEST), exists: Boolean(outputManifest) },
      "Token output manifest is missing.",
    ),
    gate(
      "required-outputs-match-manifest",
      outputs.length === REQUIRED_OUTPUTS.length && failingOutputs.length === 0,
      { failingOutputs },
      "One or more required token outputs are missing, stale, or lack generated-output evidence.",
    ),
    gate(
      "tokens-package-exports-outputs",
      missingExports.length === 0,
      { missingExports, exports: requiredExportTargets },
      "The tokens package does not export every required generated output.",
    ),
  ];
  const status = gates.every((item) => item.status === "PASS") ? "pass" : "fail";
  const ownershipDebt = gates.filter((item) => item.status !== "PASS").length
    + missingRequiredSources.length
    + failingOutputs.length
    + unownedSourceFiles.length
    + missingExports.length;
  const report = {
    generatedAt: new Date().toISOString(),
    scope: "Token ownership matrix for Style Dictionary phase 1",
    status,
    ownershipDebt,
    totals: {
      sourceFiles: allTokenSourceFiles.length,
      sourceTokens: currentSourceTokenCount,
      requiredSourceFamilies: sources.length,
      requiredOutputs: REQUIRED_OUTPUTS.length,
      matchingOutputs: outputs.filter((row) => row.status === "PASS").length,
    },
    gates,
    sourceOwnership: sources,
    outputOwnership: outputs,
  };
  const summary = {
    status,
    ownershipDebt,
    totals: report.totals,
    gates: gates.map((item) => [item.id, item.status]),
  };

  if (CHECK) {
    console.log(JSON.stringify(summary, null, 2));
    if (status !== "pass") process.exitCode = 1;
    return;
  }

  fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
  fs.writeFileSync(OUT_JSON, `${JSON.stringify(report, null, 2)}\n`);

  const lines = [
    "# Token Ownership Matrix",
    "",
    `Status: **${status}**`,
    "",
    "This report defines token ownership for phase 1: family token JSON files are source, Style Dictionary outputs are generated artifacts, and package exports expose generated outputs.",
    "",
    "## Totals",
    "",
    `- Source files: ${report.totals.sourceFiles}`,
    `- Source tokens: ${report.totals.sourceTokens}`,
    `- Required source families: ${report.totals.requiredSourceFamilies}`,
    `- Required outputs: ${report.totals.requiredOutputs}`,
    `- Matching outputs: ${report.totals.matchingOutputs}`,
    `- Ownership debt: ${ownershipDebt}`,
    "",
    "## Gates",
    "",
    "| Gate | Status | Evidence |",
    "| --- | --- | --- |",
    ...gates.map((item) => `| \`${item.id}\` | ${item.status} | \`${JSON.stringify(item.evidence)}\` |`),
    "",
    "## Source Ownership",
    "",
    "| Layer | Family | Status | Tokens | File |",
    "| --- | --- | --- | ---: | --- |",
    ...sources.map((row) => `| ${row.layer} | ${row.family} | ${row.status} | ${row.tokenCount} | \`${row.file}\` |`),
    "",
    "## Output Ownership",
    "",
    "| Output | Status | Owner |",
    "| --- | --- | --- |",
    ...outputs.map((row) => `| \`${row.file}\` | ${row.status} | ${row.owner} |`),
    "",
  ];
  fs.writeFileSync(OUT_MD, `${lines.join("\n")}\n`);
  console.log(JSON.stringify(summary, null, 2));
  if (status !== "pass") process.exitCode = 1;
}

main();
